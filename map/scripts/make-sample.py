def emit(out, layer, rank, closed, name, pts):
    out.append(f"F {layer} {rank} {1 if closed else 0} {len(pts)} {name}")
    out.append(" ".join(f"{lon:.6f} {lat:.6f}" for lat, lon in pts))


def main():
    out = ["# termap 1"]
    for layer, rank, name, pts in LINES:
        emit(out, layer, rank, False, name, pts)
    for layer, rank, name, pts in POLYS:
        emit(out, layer, rank, True, name, pts + [pts[0]])
    for name, lat, lon, rank in PLACES:
        emit(out, L_PLACE, rank, False, name, [(lat, lon)])
    for name, lat, lon, rank in LANDMARKS:
        emit(out, L_MARK, rank, False, name, [(lat, lon)])

    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    dst = os.path.join(root, "assets", "mumbai-sample.tmap")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {dst}: {len(LINES) + len(POLYS) + len(PLACES) + len(LANDMARKS)} features")


if __name__ == "__main__":
    main()
